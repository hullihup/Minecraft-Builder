    public static void give(Player p, String id, double amount) {
        Material m = Material.matchMaterial(id == null ? "" : id.trim());
        if (m == null || !m.isItem() || m.isAir()) {
            __MAIN__.INSTANCE.getLogger().warning("Unknown item: " + id);
            return;
        }
        int left = Math.max(1, (int) amount);
        while (left > 0) {
            int n = Math.min(left, m.getMaxStackSize());
            p.getInventory().addItem(new ItemStack(m, n)).values()
                    .forEach(rest -> p.getWorld().dropItemNaturally(p.getLocation(), rest));
            left -= n;
        }
    }

