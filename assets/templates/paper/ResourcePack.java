package __PKG__;

import com.sun.net.httpserver.HttpServer;
import java.io.InputStream;
import java.io.OutputStream;
import java.net.InetSocketAddress;
import java.net.URI;
import java.security.MessageDigest;
import java.util.HexFormat;
import java.util.UUID;
import java.util.concurrent.Executors;
import net.kyori.adventure.resource.ResourcePackInfo;
import net.kyori.adventure.resource.ResourcePackRequest;
import org.bukkit.entity.Player;
import org.bukkit.plugin.java.JavaPlugin;

/**
 * Serves the bundled resource pack (resourcepack.zip inside the plugin jar) with a
 * tiny built-in web server and sends it to players. Generated by Minecraft Builder.
 *
 * Settings are in plugins/<plugin>/config.yml under "resource-pack".
 */
public final class ResourcePack {
    private static HttpServer server;
    private static byte[] data;
    private static String sha1;
    private static UUID id;
    private static JavaPlugin plugin;

    private ResourcePack() {}

    public static void init(JavaPlugin p) {
        plugin = p;
        try (InputStream in = p.getResource("resourcepack.zip")) {
            if (in == null) {
                p.getLogger().warning("resourcepack.zip is missing in the plugin jar");
                return;
            }
            data = in.readAllBytes();
            sha1 = HexFormat.of().formatHex(MessageDigest.getInstance("SHA-1").digest(data));
            id = UUID.nameUUIDFromBytes(data);
            int port = p.getConfig().getInt("resource-pack.port", __PORT__);
            server = HttpServer.create(new InetSocketAddress(port), 0);
            server.createContext("/pack.zip", ex -> {
                ex.getResponseHeaders().add("Content-Type", "application/zip");
                ex.sendResponseHeaders(200, data.length);
                try (OutputStream out = ex.getResponseBody()) {
                    out.write(data);
                }
            });
            server.setExecutor(Executors.newFixedThreadPool(2));
            server.start();
            p.getLogger().info("Resource pack (" + Math.max(1, (data.length + 1023) / 1024) + " KB) is served on port " + port);
        } catch (Exception e) {
            p.getLogger().severe("Could not start the resource pack server: " + e);
        }
    }

    public static void stop() {
        if (server != null) {
            server.stop(0);
            server = null;
        }
    }

    /** Download address for this player: config value or the address the player connected with. */
    static String url(Player player) {
        String host = plugin.getConfig().getString("resource-pack.public-address", "").trim();
        if (host.isEmpty() && player.getVirtualHost() != null) {
            host = player.getVirtualHost().getHostString();
        }
        if (host.isEmpty()) host = "localhost";
        int port = plugin.getConfig().getInt("resource-pack.port", __PORT__);
        return "http://" + host + ":" + port + "/pack.zip";
    }

    public static void send(Player player) {
        if (data == null || player == null) return;
        boolean required = plugin.getConfig().getBoolean("resource-pack.required", __REQUIRED__);
        String prompt = plugin.getConfig().getString("resource-pack.prompt", "");
        ResourcePackInfo info = ResourcePackInfo.resourcePackInfo(id, URI.create(url(player)), sha1);
        player.sendResourcePacks(ResourcePackRequest.resourcePackRequest()
                .packs(info)
                .required(required)
                .replace(true)
                .prompt(Util.color(prompt)));
    }
}
