    public static ServerLevel level(String name) {
        String n = name == null ? "" : name.trim().toLowerCase(Locale.ROOT);
        switch (n) {
            case "", "world", "overworld" -> n = "minecraft:overworld";
            case "world_nether", "nether" -> n = "minecraft:the_nether";
            case "world_the_end", "end" -> n = "minecraft:the_end";
            default -> { }
        }
        ServerLevel l = SERVER.getLevel(ResourceKey.create(Registries.DIMENSION, id(n)));
        return l != null ? l : SERVER.overworld();
    }

